// Reads the first JSON object out of a model reply ("Here you go: {...}" or a ```json block).
// Returns null instead of throwing, so callers can fall back to plain rules.
export function firstJsonObject(text: string): Record<string, unknown> | null {
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start < 0 || end <= start) return null;
  try {
    const v = JSON.parse(text.slice(start, end + 1));
    return v && typeof v === 'object' && !Array.isArray(v) ? v : null;
  } catch {
    return null;
  }
}
